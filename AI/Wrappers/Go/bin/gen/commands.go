package main

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

const genHeader = "// Code generated by AI/Wrappers/Go/bin/gen; DO NOT EDIT.\n\n" +
	"/* This file is part of the Spring engine (GPL v2 or later), see LICENSE.html */\n\n"

type cmdTopic struct {
	enum  string // COMMAND_UNIT_BUILD
	value string // "35"
}

type cmdField struct {
	ctype string
	name  string
}

type command struct {
	cStruct string // SBuildUnitCommand
	topic   string // COMMAND_UNIT_BUILD
	hint    string // Unit_build (may be empty)
	fields  []cmdField
	skip    string // reason if not generated
}

var (
	topicEnumRE = regexp.MustCompile(`(?s)enum\s+CommandTopic\s*\{(.*?)\}`)
	topicLineRE = regexp.MustCompile(`(COMMAND_\w+)\s*=\s*(\d+)`)
	cmdStructRE = regexp.MustCompile(`(?s)struct\s+(S\w+)\s*\{(.*?)\}\s*;\s*//\$\s*(COMMAND_\w+)([^\n]*)`)
)

func parseCommandTopics(src string) []cmdTopic {
	var topics []cmdTopic
	m := topicEnumRE.FindStringSubmatch(src)
	if m == nil {
		return topics
	}
	for _, lm := range topicLineRE.FindAllStringSubmatch(m[1], -1) {
		topics = append(topics, cmdTopic{enum: lm[1], value: lm[2]})
	}
	return topics
}

func parseCommands(src string) []command {
	var cmds []command
	for _, m := range cmdStructRE.FindAllStringSubmatch(src, -1) {
		c := command{
			cStruct: m[1],
			topic:   m[3],
		}
		if rest := strings.Fields(m[4]); len(rest) > 0 && !strings.Contains(rest[0], ":") {
			c.hint = rest[0]
		}
		c.fields = parseCmdFields(m[2])
		classifyCommand(&c)
		cmds = append(cmds, c)
	}
	sort.Slice(cmds, func(i, j int) bool { return cmds[i].cStruct < cmds[j].cStruct })
	return cmds
}

func parseCmdFields(body string) []cmdField {
	var fields []cmdField
	for _, piece := range strings.Split(body, ";") {
		// drop comments and whitespace
		var lines []string
		for _, ln := range strings.Split(piece, "\n") {
			ln = strings.TrimSpace(ln)
			if ln == "" || strings.HasPrefix(ln, "//") || strings.HasPrefix(ln, "/*") || strings.HasPrefix(ln, "*") {
				continue
			}
			lines = append(lines, ln)
		}
		decl := strings.TrimSpace(strings.Join(lines, " "))
		if decl == "" {
			continue
		}
		ps := splitParams(decl)
		if len(ps) == 1 {
			fields = append(fields, cmdField{ctype: ps[0].ctype, name: ps[0].name})
		}
	}
	return fields
}

func classifyCommand(c *command) {
	for _, f := range c.fields {
		if strings.HasPrefix(f.name, "ret_") {
			c.skip = "has output field " + f.name
			return
		}
	}
}

// emitCommands renders command_gen.go.
func emitCommands(topics []cmdTopic, cmds []command) string {
	// Render senders first so imports can reflect what they actually use.
	var senders strings.Builder
	var skipped []string
	for _, c := range cmds {
		if c.skip != "" {
			skipped = append(skipped, c.cStruct+" ("+c.skip+")")
			continue
		}
		senders.WriteString(commandGo(c))
	}
	usesRuntime := strings.Contains(senders.String(), "runtime.")

	var b strings.Builder
	b.WriteString(genHeader)
	b.WriteString("package springai\n\n")
	b.WriteString("/*\n")
	b.WriteString("#cgo CFLAGS: -I${SRCDIR}/../../../../../rts -I${SRCDIR}/../../../../../rts/ExternalAI/Interface\n\n")
	b.WriteString("#include <stdlib.h>\n#include <stdbool.h>\n\n#include \"AISCommands.h\"\n")
	b.WriteString("*/\nimport \"C\"\n\n")
	if usesRuntime {
		b.WriteString("import (\n\t\"runtime\"\n\t\"unsafe\"\n)\n\n")
	} else {
		b.WriteString("import \"unsafe\"\n\n")
	}

	// topic constants
	b.WriteString("// Command topics, mirroring enum CommandTopic in AISCommands.h.\n")
	b.WriteString("const (\n")
	for _, t := range topics {
		b.WriteString(fmt.Sprintf("\t%s CommandTopic = %s\n", topicGoName(t.enum), t.value))
	}
	b.WriteString(")\n\n")

	b.WriteString(senders.String())

	if len(skipped) > 0 {
		b.WriteString("\n// The following commands were not generated and need hand-wiring\n")
		b.WriteString("// (they carry engine-written ret_ output fields):\n")
		for _, s := range skipped {
			b.WriteString("//   - " + s + "\n")
		}
	}
	return b.String()
}

func topicGoName(enum string) string {
	rest := strings.TrimPrefix(enum, "COMMAND_")
	var sb strings.Builder
	sb.WriteString("Command")
	for _, p := range strings.Split(rest, "_") {
		if p == "" {
			continue
		}
		sb.WriteString(strings.ToUpper(p[:1]) + strings.ToLower(p[1:]))
	}
	return sb.String()
}

func commandGo(c command) string {
	structGo := strings.TrimPrefix(c.cStruct, "S") // BuildUnitCommand
	method := goName(c.hint)
	if method == "" {
		method = structGo
	}

	// Build the Go struct (inputs only) and the marshaling body in lockstep.
	var goFields []string
	var preps []string
	var assigns []string
	needPin := false // set when a Go pointer is stored into the C struct

	i := 0
	for i < len(c.fields) {
		f := c.fields[i]
		hasSize := i+1 < len(c.fields) && c.fields[i+1].name == f.name+"_size"
		gf := goFieldName(f.name)

		if stars(f.ctype) == 0 {
			goType, toC, _, ok := scalarGo(f.ctype)
			if !ok {
				// unknown scalar -> bail out of this command
				return fmt.Sprintf("// command %s skipped: unhandled field type %s %s\n\n", c.cStruct, f.ctype, f.name)
			}
			if goType == "bool" {
				goFields = append(goFields, gf+" bool")
				assigns = append(assigns, fmt.Sprintf("c.%s = C.bool(cmd.%s)", f.name, gf))
			} else {
				goFields = append(goFields, gf+" "+goType)
				assigns = append(assigns, fmt.Sprintf("c.%s = %s", f.name, fmt.Sprintf(toC, "cmd."+gf)))
			}
			i++
			continue
		}

		// pointers
		switch {
		case strings.Contains(f.ctype, "char") && stars(f.ctype) == 1:
			goFields = append(goFields, gf+" string")
			cv := "c_" + f.name
			preps = append(preps,
				cv+" := C.CString(cmd."+gf+")",
				"defer C.free(unsafe.Pointer("+cv+"))")
			assigns = append(assigns, fmt.Sprintf("c.%s = %s", f.name, cv))
			i++

		case scalarBase(f.ctype) == "float" && strings.Contains(f.name, "posF3"):
			goFields = append(goFields, gf+" AIFloat3")
			cv := "c_" + f.name
			preps = append(preps, fmt.Sprintf("%s := [3]C.float{C.float(cmd.%s.X), C.float(cmd.%s.Y), C.float(cmd.%s.Z)}", cv, gf, gf, gf))
			assigns = append(assigns,
				fmt.Sprintf("pinner.Pin(&%s[0])", cv),
				fmt.Sprintf("c.%s = &%s[0]", f.name, cv))
			needPin = true
			i++

		case hasSize:
			base := scalarBase(f.ctype)
			elemGo, toC, _, ok := scalarGo(base)
			if !ok {
				return fmt.Sprintf("// command %s skipped: unhandled array element %s\n\n", c.cStruct, base)
			}
			goFields = append(goFields, gf+" []"+elemGo)
			cv := "c_" + f.name
			preps = append(preps,
				fmt.Sprintf("%s := make([]C.%s, len(cmd.%s))", cv, base, gf),
				fmt.Sprintf("for i, v := range cmd.%s {\n\t\t%s[i] = %s\n\t}", gf, cv, fmt.Sprintf(toC, "v")))
			assigns = append(assigns,
				fmt.Sprintf("if len(%s) > 0 {\n\t\tpinner.Pin(&%s[0])\n\t\tc.%s = (*C.%s)(&%s[0])\n\t}", cv, cv, f.name, base, cv),
				fmt.Sprintf("c.%s_size = C.int(len(cmd.%s))", f.name, gf))
			needPin = true
			i += 2

		default:
			return fmt.Sprintf("// command %s skipped: unhandled pointer field %s %s\n\n", c.cStruct, f.ctype, f.name)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// %s mirrors struct %s (%s).\n", structGo, c.cStruct, c.topic)
	fmt.Fprintf(&b, "type %s struct {\n", structGo)
	for _, gfld := range goFields {
		b.WriteString("\t" + gfld + "\n")
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "// %s sends a %s command. Returns the engine's result code (0 = ok).\n", method, c.topic)
	fmt.Fprintf(&b, "func (cb *Callback) %s(cmd %s) int {\n", method, structGo)
	for _, p := range preps {
		b.WriteString("\t" + p + "\n")
	}
	if needPin {
		// Pin the Go buffers stored into the C struct: cgo forbids passing to C
		// a pointer to Go memory that itself holds (unpinned) Go pointers.
		b.WriteString("\tvar pinner runtime.Pinner\n")
		b.WriteString("\tdefer pinner.Unpin()\n")
	}
	fmt.Fprintf(&b, "\tvar c C.struct_%s\n", c.cStruct)
	for _, a := range assigns {
		b.WriteString("\t" + a + "\n")
	}
	fmt.Fprintf(&b, "\treturn cb.handleCommand(CommandToIDEngine, -1, %s, unsafe.Pointer(&c))\n}\n\n", topicGoName(c.topic))

	return b.String()
}

func countEmittedCmds(cmds []command) int {
	n := 0
	for _, c := range cmds {
		if c.skip == "" {
			n++
		}
	}
	return n
}
